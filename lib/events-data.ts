/** True until the day after the event ends. `today` is YYYY-MM-DD. */
export function isEventCurrent(event: Pick<SouthportEvent, "isoDate" | "endIsoDate">, today: string): boolean {
  return (event.endIsoDate ?? event.isoDate) >= today;
}

function todayISO(): string {
  return new Date().toISOString().slice(0, 10);
}

/** Events that have not yet ended, soonest first */
export function getUpcomingEvents(limit?: number, today: string = todayISO()): SouthportEvent[] {
  const upcoming = EVENTS.filter((e) => isEventCurrent(e, today)).sort((a, b) => a.isoDate.localeCompare(b.isoDate));
  return limit ? upcoming.slice(0, limit) : upcoming;
}

/** Events that have not yet ended, grouped by the month they start in ("November 2026") */
export function getEventsByMonth(today: string = todayISO()): Record<string, SouthportEvent[]> {
  const grouped: Record<string, SouthportEvent[]> = {};
  for (const event of getUpcomingEvents(undefined, today)) {
    const d = new Date(event.isoDate + "T12:00:00Z");
    const label = d.toLocaleDateString("en-GB", { month: "long", year: "numeric", timeZone: "UTC" });
    if (!grouped[label]) grouped[label] = [];
    grouped[label].push(event);
  }
  return grouped;
}
