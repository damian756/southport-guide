// ── Events calendar data ─────────────────────────────────────────────────
// Static events for the home page, the /events calendar, the nav and the
// weekly email. An event drops off every list the day after it ends
// (`endIsoDate`, or `isoDate` for a one-day event), so a past event needs no
// edit. Add next year's dates as new entries once the organiser publishes
// them, with the page they came from in `source`. Do not guess dates.
// Approved events from the database (Eventbrite sync) are merged in on /events.

export interface SouthportEvent {
  title: string;
  /** ISO date string (YYYY-MM-DD) used for sorting / filtering */
  isoDate: string;
  /** ISO end date for multi-day events (YYYY-MM-DD). Omit for single-day events. */
  endIsoDate?: string;
  /** Human-readable date label shown on cards */
  dayLabel: string;
  venue: string;
  category: string;
  emoji: string;
  /** true: free to attend; false: tickets or an entry fee; leave out when the organiser's page does not say */
  free?: boolean;
  link: string;
  /** When set, links to /guides/{guideSlug} instead of the external link */
  guideSlug?: string;
  /** 1-2 sentence summary shown on event cards and used for SEO content density */
  description?: string;
  /** Human-readable time string, e.g. "7:30pm" or "1pm–10pm" */
  time?: string;
  /** Where the details were checked, and when (not shown on the site) */
  source?: string;
}

